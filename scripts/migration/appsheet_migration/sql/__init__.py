"""SQL generation: one module per target table, assembled by `build_script`."""
from __future__ import annotations

from ..config import SCRIPT_PATH_FOR_HEADER
from ..models import MigrationData
from .assets import assets_section
from .employees import employees_section
from .leave import leave_section
from .lookups import lookup_section
from .overtime import overtime_section


def build_script(data: MigrationData, employee_conflict: str, source_name: str) -> str:
    """The whole import as one transaction. `employee_conflict`: "update" or "skip" (existing employee codes)."""
    chunks = [
        f"-- Generated by {SCRIPT_PATH_FOR_HEADER} from {source_name}",
        f"-- {len(data.employees)} employees, {len(data.overtime)} overtime requests, "
        f"{len(data.leave)} leave requests, {len(data.assets)} asset requests",
        "-- Idempotent: deterministic UUIDs + ON CONFLICT. Contains personal data - do not commit.",
        "BEGIN;\n",
        *lookup_section(data),
        *employees_section(data, employee_conflict),
        *overtime_section(data),
        *leave_section(data),
        *assets_section(data),
        "COMMIT;",
    ]
    return "\n".join(chunks) + "\n"
